-- ============================================================
-- PL/SQL の基礎（1. PL/SQLとは / 2. 基本構造（ブロック））
-- ============================================================
-- 最初に、画面に結果を表示するための設定をします。
-- この設定がないと、DBMS_OUTPUT.PUT_LINE の結果が表示されません。
SET SERVEROUTPUT ON

-- ------------------------------------------------------------
-- 最小のブロック（BEGIN と END だけ）
--  1つのブロックを書いたら、最後の / まで選んで実行する
-- 実行すると Hello, PL/SQL! と表示されます。
BEGIN 
    DBMS_OUTPUT.PUT_LINE('Hello, PL/SQL!');
END;
